\getenv main_password MAIN_DB_PASSWORD
\getenv auth_password AUTH_DB_PASSWORD
CREATE ROLE main_app LOGIN PASSWORD :'main_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE auth_app LOGIN PASSWORD :'auth_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE DATABASE main_db OWNER main_app;
CREATE DATABASE auth_db OWNER auth_app;
REVOKE CONNECT, TEMPORARY ON DATABASE main_db FROM PUBLIC;
REVOKE CONNECT, TEMPORARY ON DATABASE auth_db FROM PUBLIC;
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE main_db TO main_app;
GRANT CONNECT, TEMPORARY ON DATABASE auth_db TO auth_app;
